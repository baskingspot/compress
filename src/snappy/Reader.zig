    r.reader.toss(1);
    try testing.expectError(error.ReadFailed, r.reader.takeDelimiterExclusive('\n'));
    try testing.expectEqual(Error.StreamTooLong, r.err.?);
}

/// A complete single-chunk stream carrying `bytes` as a raw data chunk,
/// with the correct masked CRC-32C. Asserts `buf` can hold it.
fn rawChunk(bytes: []const u8, buf: []u8) []u8 {
    const payload_len = Writer.chunk_crc_len + bytes.len;
    const need = Writer.identifier.len + Writer.chunk_header_len + payload_len;
    assert(need <= buf.len);
    @memcpy(buf[0..Writer.identifier.len], Writer.identifier);
    var pos: usize = Writer.identifier.len;
    buf[pos] = 0x01;
    buf[pos + 1] = @truncate(payload_len);
    buf[pos + 2] = @truncate(payload_len >> 8);
    buf[pos + 3] = @truncate(payload_len >> 16);
    pos += Writer.chunk_header_len;
    writeInt(u32, buf[pos..][0..4], crc32c.mask(crc32c.crc32c(0, bytes)));
    pos += Writer.chunk_crc_len;
    fastmem.copy(u8, buf[pos..][0..bytes.len], bytes);
    pos += bytes.len;
    return buf[0..pos];
}

/// A complete single-chunk stream carrying `block` as a compressed data
/// chunk (`kind` 0x00) with `checksum` as its stored masked CRC-32C.
/// Asserts `buf` can hold it.
fn compressedChunk(block: []const u8, checksum: u32, buf: []u8) []u8 {
    const payload_len = Writer.chunk_crc_len + block.len;
    const need = Writer.identifier.len + Writer.chunk_header_len + payload_len;
    assert(need <= buf.len);
    @memcpy(buf[0..Writer.identifier.len], Writer.identifier);
    var pos: usize = Writer.identifier.len;
    buf[pos] = 0x00;
    buf[pos + 1] = @truncate(payload_len);
    buf[pos + 2] = @truncate(payload_len >> 8);
    buf[pos + 3] = @truncate(payload_len >> 16);
    pos += Writer.chunk_header_len;
    writeInt(u32, buf[pos..][0..4], checksum);
    pos += Writer.chunk_crc_len;
    fastmem.copy(u8, buf[pos..][0..block.len], block);
    pos += block.len;
    return buf[0..pos];
}

/// Append a chunk with `kind` and `payload`; returns the bytes written.
fn putChunk(buf: []u8, kind: u8, payload: []const u8) usize {
    assert(payload.len < 1 << 24);
    buf[0] = kind;
    buf[1] = @truncate(payload.len);
    buf[2] = @truncate(payload.len >> 8);
    buf[3] = @truncate(payload.len >> 16);
    fastmem.copy(u8, buf[4..][0..payload.len], payload);
    return 4 + payload.len;
}

