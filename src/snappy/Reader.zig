//! snappy.Reader: a decompressing `Io.Reader` over Google's framed snappy
//! stream (`framing_format.txt`). Read through `&r.reader`.
//!
//! The stream starts with the 10-byte identifier and is then a sequence of
//! chunks: data chunks (compressed or raw) carry a masked CRC-32C of their
//! uncompressed bytes, the identifier may repeat and is ignored, skippable and
//! padding chunks are skipped, and a reserved unskippable chunk fails the
//! stream. There is no end marker: the input's end is the stream's end, and a
//! chunk cut short is `Truncated`.
//!
//! A corrupt chunk or block returns `error.ReadFailed` with the reason in
//! `err`. Both outcomes are sticky.
//!
//! The caller's `Buffer` holds the decoded serving region (three chunks of
//! contiguous decoded reads) and, behind it, staging for one chunk's payload.
//! A `peek` or similar request for more than two contiguous chunks can return
//! `error.ReadFailed` with `err` set to `StreamTooLong`. Nothing is allocated.

