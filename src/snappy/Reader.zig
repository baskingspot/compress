/// The caller-provided buffer: the decoded serving region plus the
/// chunk-payload staging region.
pub const Buffer = [decoded_region_len + Writer.scratch_len]u8;

/// The decoded serving region: three chunks of contiguous decoded reads.
const decoded_region_len = 3 * Writer.max_chunk_len;

const Reader = @This();

/// The detailed error recorded once `state == .failed` (the interface reports
/// `error.ReadFailed`): framing errors come from this layer, block errors come
/// from `decode.DecompressError`, and `ReadFailed`/`EndOfStream` pass through
/// from the input.
pub const Error = error{
    /// The input ended inside the identifier, a chunk header, or a chunk.
    Truncated,
    /// A chunk's declared shape is invalid: a data chunk shorter than its
    /// checksum, a payload past the staging region, or a block that decodes
    /// past one chunk.
    InvalidStream,
    /// The stream does not start with the identifier, or a repeated
    /// identifier is malformed (`framing_format.txt` §4.1).
    BadStreamIdentifier,
    /// A reserved unskippable chunk type, 0x02-0x7f (`§4.5`).
    BadChunkType,
    /// A data chunk's masked CRC-32C does not match its uncompressed bytes
    /// (`§3`).
    BadChecksum,
    StreamTooLong,
} || decode.DecompressError || error{ ReadFailed, EndOfStream };

reader: Io.Reader,
input: *Io.Reader,
staging: *[Writer.scratch_len]u8,
/// The identifier's state: the first fill reads and checks it.
started: bool,
/// The stream lifecycle (src/internal/reader.zig): `streaming` until the
/// input ends cleanly at a chunk boundary (`done`) or a failure sticks
/// (`failed`, details in `err`).
state: State,
/// Detailed error once `state == .failed`; the interface reports
/// `error.ReadFailed`.
err: ?Error,

/// The `Io.Reader` entries, generated by `internal.reader.VTable`: the sticky
/// done/failed guard, the zero-length poll, and the fill-and-return-0 count
/// come from there. `fillNextChunk` is the pump; `rebase` owns the region's
/// capacity policy.
const vtable = VTable(Reader, fillNextChunk, rebase).vtable;

/// Wrap `input` (a framed snappy stream) with `buffer` for decoded output.
/// Consume through `&r.reader` (`stream`, `read`-family, `peek`-family); the
/// stream ends cleanly with `error.EndOfStream` at a chunk boundary and
/// returns `error.ReadFailed` (sticky, details in `err`) on any corrupt
/// framing, checksum, or block.
pub fn init(input: *Io.Reader, buffer: *Buffer) Reader {
    return .{
        .reader = .{
            .buffer = buffer[0..decoded_region_len],
            .seek = 0,
            .end = 0,
            .vtable = &vtable,
        },
        .input = input,
        .staging = buffer[decoded_region_len..],
        .started = false,
        .state = .streaming,
        .err = null,
    };
}

/// Read and check the identifier chunk (`§4.1`): 0xff, length 6, `sNaPpY`.
fn readIdentifier(r: *Reader) Io.Reader.Error!void {
    var header: [Writer.chunk_header_len]u8 = undefined;
    const got = r.input.readSliceShort(&header) catch |e| return fail(r, e);
    if (got == 0) {
        // A zero-byte input is the empty stream, as s2 and the previous
        // framing treat it. `Writer` emits the identifier-only form instead,
        // which is a valid stream too.
        r.state = .done;
        return error.EndOfStream;
    }
    if (got < Writer.chunk_header_len) return fail(r, error.Truncated);
    if (header[0] != 0xff) return fail(r, error.BadStreamIdentifier);
    const len = @as(usize, header[1]) | (@as(usize, header[2]) << 8) |
        (@as(usize, header[3]) << 16);
    if (len != 6) return fail(r, error.BadStreamIdentifier);
    r.input.readSliceAll(r.staging[0..6]) catch |e| return switch (e) {
        error.EndOfStream => fail(r, error.Truncated),
        else => |e2| fail(r, e2),
    };
    if (!std.mem.eql(u8, r.staging[0..6], Writer.identifier[4..10])) {
        return fail(r, error.BadStreamIdentifier);
    }
}

/// Decode the next data chunk into the serving region, appending after any
/// unconsumed bytes (sliding to the front first when the region lacks room).
/// Metadata chunks are consumed along the way. Returns 0: the data lands in
/// `reader.buffer` per the VTable contract.
fn fillNextChunk(r: *Reader) Io.Reader.Error!usize {
    if (!r.started) {
        try r.readIdentifier();
        r.started = true;
    }

    while (true) {
        var header: [Writer.chunk_header_len]u8 = undefined;
        const got = r.input.readSliceShort(&header) catch |e| return fail(r, e);
        if (got == 0) {
            // The input ended exactly at a chunk boundary: the clean end.
            r.state = .done;
            return error.EndOfStream;
        }
        if (got < Writer.chunk_header_len) return fail(r, error.Truncated);
        const kind = header[0];
        const len = @as(usize, header[1]) | (@as(usize, header[2]) << 8) |
            (@as(usize, header[3]) << 16);

        switch (kind) {
            0x00, 0x01 => {
                if (len < Writer.chunk_crc_len) return fail(r, error.InvalidStream);
                const payload_len = len - Writer.chunk_crc_len;
                if (payload_len > Writer.scratch_len) return fail(r, error.InvalidStream);
                if (kind == 0x01 and payload_len > Writer.max_chunk_len) {
                    return fail(r, error.InvalidStream);
                }
                var checksum: [Writer.chunk_crc_len]u8 = undefined;
                r.input.readSliceAll(&checksum) catch |e| return switch (e) {
                    error.EndOfStream => fail(r, error.Truncated),
                    else => |e2| fail(r, e2),
                };
                const payload = r.staging[0..payload_len];
                r.input.readSliceAll(payload) catch |e| return switch (e) {
                    error.EndOfStream => fail(r, error.Truncated),
                    else => |e2| fail(r, e2),
                };
                const decoded_len = if (kind == 0x00)
                    decode.decompressedBlockLength(payload) catch |err| return fail(r, err)
                else
                    payload_len;
                if (decoded_len > Writer.max_chunk_len) return fail(r, error.InvalidStream);

                if (r.reader.end + decoded_len > decoded_region_len) {
                    slide(r);
                    if (r.reader.end + decoded_len > decoded_region_len) {
                        return fail(r, error.StreamTooLong);
                    }
                }
                const dest = r.reader.buffer[r.reader.end..][0..decoded_len];
                if (kind == 0x00) {
                    const n = decode.decompressBlock(payload, dest) catch |err| return fail(r, err);
                    assert(n == decoded_len);
                } else {
                    fastmem.copy(u8, dest, payload);
                }
                if (crc32c.mask(crc32c.crc32c(0, dest)) != readInt(u32, &checksum)) {
                    return fail(r, error.BadChecksum);
                }
                r.reader.end += decoded_len;
                // A zero-length data chunk carries no output; keep reading
                // rather than report a fill that made no progress.
                if (decoded_len == 0) continue;
                return 0;
            },
            0xff => {
                // A repeated identifier is legal and ignored (`§4.1`).
                if (len != 6) return fail(r, error.BadStreamIdentifier);
                r.input.readSliceAll(r.staging[0..6]) catch |e| return switch (e) {
                    error.EndOfStream => fail(r, error.Truncated),
                    else => |e2| fail(r, e2),
                };
                if (!std.mem.eql(u8, r.staging[0..6], Writer.identifier[4..10])) {
                    return fail(r, error.BadStreamIdentifier);
                }
            },
            0x02...0x7f => return fail(r, error.BadChunkType),
            else => {
                // 0x80-0xfd are skippable and 0xfe is padding (`§4.4`, `§4.6`).
                r.input.discardAll(len) catch |e| return switch (e) {
                    error.EndOfStream => fail(r, error.Truncated),
                    else => |e2| fail(r, e2),
                };
            },
        }
    }
}

fn fail(r: *Reader, err: Error) Io.Reader.Error {
    return internal.reader.fail(Error, &r.state, &r.err, err);
}

/// Slide the unconsumed bytes to the front of the serving region, so the
/// region then has `decoded_region_len - end` contiguous free. Shared by
/// the pump (making room for a fresh chunk) and the rebase hook.
fn slide(r: *Reader) void {
    const keep = r.reader.end - r.reader.seek;
    fastmem.move(u8, r.reader.buffer[0..keep], r.reader.buffer[r.reader.seek..][0..keep]);
    r.reader.seek = 0;
    r.reader.end = keep;
}

/// The rebase hook for the generated entries: slide the unconsumed bytes to
/// the front, so the serving region then has `decoded_region_len - end`
/// contiguous free.
///
/// A capacity past the serving region (an oversized `peek`, say) returns
/// `StreamTooLong`; std's default `rebase` would assert on it.
fn rebase(r: *Reader, capacity: usize) Io.Reader.RebaseError!void {
    slide(r);
    if (capacity > decoded_region_len) return fail(r, error.StreamTooLong);
}

